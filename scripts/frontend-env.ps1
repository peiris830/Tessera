<#
.SYNOPSIS
    Write frontend/.env.local from the deployed stacks' SSM parameters.

.DESCRIPTION
    The frontend needs the Catalogue API URL and the Cognito settings. They differ per
    deployment, so they aren't committed: this script reads them from SSM Parameter Store
    (ADR 0002) and writes frontend/.env.local, which Vite loads and git ignores.
    frontend/.env.example lists the same variable names. Rerun after redeploying a stack.
    None of the values are secrets: they all end up in the public JavaScript bundle.

.EXAMPLE
    $env:AWS_PROFILE = "tessera-dev"
    .\scripts\frontend-env.ps1
#>
param(
    [ValidateSet("dev")]
    [string]$Environment = "dev"
)

$ErrorActionPreference = "Stop"
$repo = Split-Path -Parent $PSScriptRoot

# Variable name -> SSM parameter (under /tessera/<env>/)
$variables = [ordered]@{
    VITE_CATALOGUE_API_URL     = "catalogue/api-url"
    VITE_COGNITO_AUTHORITY     = "cognito/issuer-url"
    VITE_COGNITO_CLIENT_ID     = "cognito/app-client-id"
    VITE_COGNITO_HOSTED_UI_URL = "cognito/hosted-ui-url"
}

# Keep .env.example (the committed documentation) and this script in step.
$example = Get-Content (Join-Path $repo "frontend\.env.example") |
    Where-Object { $_ -match '^[A-Z_]+=' } | ForEach-Object { ($_ -split '=')[0] }
if (Compare-Object @($example | Sort-Object) @($variables.Keys | Sort-Object)) {
    throw "frontend/.env.example and this script list different variables; update both."
}

$names = $variables.Values | ForEach-Object { "/tessera/$Environment/$_" }
$json = aws ssm get-parameters --names @names --output json
if ($LASTEXITCODE -ne 0) { throw "Reading SSM parameters failed (is AWS_PROFILE set and are you signed in?)" }
$result = $json | ConvertFrom-Json

if ($result.InvalidParameters.Count -gt 0) {
    throw "Missing SSM parameters: $($result.InvalidParameters -join ', '). Deploy the shared and catalogue stacks first."
}
$values = @{}
foreach ($p in $result.Parameters) { $values[$p.Name] = $p.Value }

$lines = @(
    "# Generated by scripts/frontend-env.ps1 from SSM (/tessera/$Environment/...). Don't edit or commit;"
    "# rerun the script after redeploying. Variable names: .env.example."
)
foreach ($entry in $variables.GetEnumerator()) {
    $lines += "$($entry.Key)=$($values["/tessera/$Environment/$($entry.Value)"])"
}

$target = Join-Path $repo "frontend\.env.local"
# UTF-8 without BOM and LF endings, as Vite and the other tooling expect.
[IO.File]::WriteAllText($target, (($lines -join "`n") + "`n"), [Text.UTF8Encoding]::new($false))
Write-Host "Wrote $target" -ForegroundColor Green
$variables.Keys | ForEach-Object { Write-Host "  $_" }
